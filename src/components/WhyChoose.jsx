const iconKeys = ['premium', 'driver', 'clean', 'time', 'pricing', 'support'];

export default function WhyChoose() {
  const [isVisible, setIsVisible] = useState(false);
  const sectionRef = useRef(null);

  useEffect(() => {
    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          setIsVisible(true);
          observer.unobserve(entry.target);
        }
      },
      { threshold: 0.15 }
    );

    if (sectionRef.current) {
      observer.observe(sectionRef.current);
    }

    return () => observer.disconnect();
  }, []);

  return (
    <section className="why-choose" ref={sectionRef}>
      <div className="container">
        <div className="why-choose__grid">
          {WHY_CHOOSE_US.map((item, index) => (
            <div 
              key={index} 
              className={`why-choose__item ${isVisible ? 'why-choose__item--visible' : ''}`}
              style={{ transitionDelay: `${index * 0.08}s` }}
            >
              <div className="why-choose__icon">
                {icons[iconKeys[index]]}
              </div>
              <h3 className="why-choose__title">{item.title}</h3>
              <p className="why-choose__desc">{item.desc}</p>
            </div>
          ))}
        </div>
      </div>
    </section>
  );
}